// Capturas da prévia com Chromium headless (WebGL via SwiftShader: FPS aqui não representa o equipamento real).
import { chromium } from 'playwright-core'
const out = process.argv[2] || 'shots'
const url = process.argv[3] || 'http://localhost:4173/'
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] })
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } })
const logs = []
page.on('console', (m) => logs.push(`[${m.type()}] ${m.text()}`))
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`))
await page.goto(url)
await page.waitForTimeout(4000)
await page.screenshot({ path: `${out}/01-menu.png` })
await page.keyboard.press('Enter')
await page.waitForTimeout(3000)
await page.screenshot({ path: `${out}/02-corrida.png` })
await page.keyboard.press('ArrowLeft')
await page.waitForTimeout(80)
await page.screenshot({ path: `${out}/03-troca-faixa.png` })
await page.waitForTimeout(1200)
await page.keyboard.press('Space')
await page.waitForTimeout(300)
await page.screenshot({ path: `${out}/04-pulo.png` })
await page.waitForTimeout(1200)
await page.keyboard.press('ArrowDown')
await page.waitForTimeout(250)
await page.screenshot({ path: `${out}/05-deslize.png` })
await page.waitForTimeout(1200)
await page.keyboard.press('Digit2')
await page.waitForTimeout(700)
await page.screenshot({ path: `${out}/06-comemorar.png` })
await page.waitForTimeout(2500)
await page.keyboard.press('Digit1')
await page.waitForTimeout(500)
await page.screenshot({ path: `${out}/07-impacto.png` })
await page.setViewportSize({ width: 820, height: 1180 })
await page.waitForTimeout(2500)
await page.screenshot({ path: `${out}/08-tablet-retrato.png` })
const fps = await page.locator('.lr-mono').textContent()
console.log('stats:', JSON.stringify(await page.evaluate(() => window.__lumisStats)))
console.log('chip:', fps)
console.log(logs.filter((l) => !l.includes('GPU stall')).slice(0, 20).join('\n'))
await browser.close()
